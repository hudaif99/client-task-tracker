import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { createAuthOptions } from "./auth-options.ts";
import { db } from "./db.ts";

try {
  const options = createAuthOptions(db, process.env);
  // Introspect and compile only. Never call plan.runMigrations() here.
  const plan = await getMigrations(options, { throwOnUnsafe: false });
  if (plan.unsafeChanges.length || plan.schemaProblems.length || plan.toBeAdded.length) {
    throw new Error("Existing auth tables need review. No schema file was generated.");
  }
  const expected = new Set(["auth_user", "auth_session", "auth_account", "auth_verification"]);
  if (plan.toBeCreated.length !== expected.size || plan.toBeCreated.some(table => !expected.has(table.table))) {
    throw new Error("Expected four new auth tables. Review existing tables before generating a bootstrap migration.");
  }

  const directory = new URL("../generated/", import.meta.url);
  const output = new URL("auth-schema.sql", directory);
  await mkdir(directory, { recursive: true });
  const sql = await plan.compileMigrations();
  await writeFile(output, `-- Generated by Better Auth. Review before adding to a versioned migration.\n${sql}\n`, "utf8");
  console.log(`Generated ${fileURLToPath(output)}`);
  console.log("Four auth tables planned. No database changes were applied.");
} catch (error) {
  console.error(error instanceof Error ? error.message : "Auth schema generation failed.");
  process.exitCode = 1;
} finally {
  await db.end();
}
